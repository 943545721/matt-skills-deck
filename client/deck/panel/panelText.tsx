const TABLES = { en: EN, zh: ZH };

function fill(text: string, vars?: Readonly<Record<string, string | number>>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/** 纯函数版本：给测试与非组件代码用。 */
export function panelText(
  locale: string,
  key: PanelKey,
  vars?: Readonly<Record<string, string | number>>,
): string {
  const table = locale.toLowerCase().startsWith("zh") ? TABLES.zh : TABLES.en;
  return fill(table[key], vars);
}

export interface PanelTextFn {
  (key: PanelKey, vars?: Readonly<Record<string, string | number>>): string;
}

/** 组件入口：语言跟随宿主，不提供独立开关。 */
export function usePanelText(): { t: PanelTextFn; zh: boolean } {
  const { locale } = useDeckText();
  return useMemo(() => {
    const zh = locale.toLowerCase().startsWith("zh");
    return { t: (key, vars) => panelText(locale, key, vars), zh };
  }, [locale]);
}
